from typing import Protocol, List
from datetime import date
from typing_extensions import runtime_checkable
from abc import ABC, abstractmethod


# --- Domain models (placeholders) ---

class User: ...
class ChatMetaData: ...
class ModelData: ...
class QuotaConfig: ...
class UsageData: ...


class IEntityRepository(ABC):
    # --------------------
    # User-related
    # --------------------
    @abstractmethod
    def get_user(self, user_id: str) -> User: ...
    @abstractmethod
    def get_user_by_email(self, email: str) -> User: ...
    @abstractmethod
    def create_user(self, user: User) -> str: ...
    @abstractmethod
    def update_user(self, user_id: str, email: str, username: str) -> None: ...

    # --------------------
    # Authentication & validation
    # --------------------
    @abstractmethod
    def check_password(self, email: str, password: str) -> bool: ...
    @abstractmethod
    def user_exists(self, email: str) -> bool: ...
    @abstractmethod
    def is_user_verified(self, user_id: str) -> bool: ...
    @abstractmethod
    def is_user_admin(self, user_id: str) -> bool: ...
    @abstractmethod
    def is_email_taken(self, email: str) -> bool: ...
    @abstractmethod
    def is_username_taken(self, username: str) -> bool: ...

    # --------------------
    # Token-related
    # --------------------
    @abstractmethod
    def get_token(self, token_id: str) -> str: ...
    @abstractmethod
    def create_token(self, prompt: str) -> str: ...
    @abstractmethod
    def change_token(self, token_id: str, token: str) -> None: ...
    @abstractmethod
    def invalidate_token(self, token_id: str) -> None: ...
    @abstractmethod
    def is_token_valid(self, token_id: str) -> bool: ...

    # --------------------
    # Chat / Conversation-related
    # --------------------
    @abstractmethod
    def get_chats(self, user_id: str) -> List[ChatMetaData]: ...
    @abstractmethod
    def get_chat(self, chat_id: str) -> ChatMetaData: ...
    @abstractmethod
    def create_chat(self, chat: ChatMetaData) -> str: ...
    @abstractmethod
    def update_chat(self, chat_id: str, chat: ChatMetaData) -> None: ...

    # --------------------
    # Message-related
    # --------------------
    @abstractmethod
    def add_message(self, chat_id: str, message: str) -> str: ...
    @abstractmethod
    def get_messages(self, chat_id: str) -> List[str]: ...
    @abstractmethod
    def change_last_message(self, chat_id: str, message: str) -> None: ...

    # --------------------
    # LLM Model-related
    # --------------------
    @abstractmethod
    def add_model(self, model_data: ModelData) -> str: ...
    @abstractmethod
    def remove_model(self, model_id: str) -> None: ...
    @abstractmethod
    def change_model(self, model_id: str, model_data: ModelData) -> None: ...
    @abstractmethod
    def get_model(self, model_id: str) -> ModelData: ...

    # --------------------
    # Quota-related
    # --------------------
    @abstractmethod
    def change_quota(self, quota: QuotaConfig) -> None: ...
    @abstractmethod
    def get_quota(self) -> QuotaConfig: ...
    @abstractmethod
    def get_user_quota_remaining(self, user_id: str, period: date) -> int: ...
    @abstractmethod
    def is_quota_exceeded(self, user_id: str) -> bool: ...

    # --------------------
    # Analytics / Usage-related
    # --------------------
    @abstractmethod
    def get_usage_data(self) -> UsageData: ...

    # --------------------
    # Profile Picture
    # --------------------
    @abstractmethod
    def save_profile_picture(self, user_id: str, file_data: bytes) -> None: ...
    @abstractmethod
    def get_profile_picture(self, user_id: str) -> bytes: ...
    @abstractmethod
    def delete_profile_picture(self, user_id: str) -> None: ...
